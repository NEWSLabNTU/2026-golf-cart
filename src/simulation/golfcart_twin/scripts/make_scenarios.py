#!/usr/bin/env python3
"""The demo routes as OpenSCENARIO scenarios (Phase 10): scenarios/route<N>.xosc from
config/routes.yaml, for scenario-world-bridge's stack on Isaac Sim (twin.launch.py scenario:=).

    python3 make_scenarios.py [--check]

Each scenario puts the cart (this package's catalog, catalogs/vehicles.xosc: newslab_golfcart)
at the route's start with the cart's own Autoware as its controller, routes it to the goal,
and passes when it is within 2 m of the goal, or fails after the timeout. The map is
$(env TWIN_MAP), the NTU twin's map directory (scripts/twin/setup.bash sets it).
"""
import sys
from pathlib import Path

import yaml

PKG = Path(__file__).resolve().parent.parent
SPEED = 2.5  # m/s, the cart's ceiling (the sim's motor)
# SSv2 refuses an entity faster than its declared maxSpeed; the motor holds 2.5 within a few
# hundredths (2.51 seen), so the scenarios declare a margin above it; likewise the
# accelerations (a stop for a pedestrian braked at 3.06 m/s^2): bounds, not commands
MAX_SPEED = 3.0


def scenario(name, r):
    s, g = r["start"], r["goal"]
    timeout = max(120.0, 3.0 * r.get("length_m", 100.0) / SPEED)
    return f"""<?xml version="1.0"?>
<!-- Generated by golfcart_twin scripts/make_scenarios.py from config/routes.yaml: do not edit. -->
<OpenSCENARIO>
  <FileHeader author="golfcart_twin" date="2026-11-08T00:00:00+00:00" description="NTU twin, route {name}: {r['title']} ({r.get('turns', 0)} turn(s), {r.get('length_m', 0)} m). The golf cart with its own Autoware." revMajor="1" revMinor="2" />
  <ParameterDeclarations />
  <CatalogLocations>
    <VehicleCatalog><Directory path="$(find-pkg-share golfcart_twin)/catalogs" /></VehicleCatalog>
  </CatalogLocations>
  <RoadNetwork>
    <LogicFile filepath="$(env TWIN_MAP)" />
  </RoadNetwork>
  <Entities>
    <ScenarioObject name="ego">
      <CatalogReference catalogName="vehicles" entryName="newslab_golfcart">
        <ParameterAssignments>
          <ParameterAssignment parameterRef="maxSpeed" value="{MAX_SPEED}" />
          <ParameterAssignment parameterRef="maxAcceleration" value="3.0" />
          <ParameterAssignment parameterRef="maxDeceleration" value="6.0" />
          <ParameterAssignment parameterRef="maxSteering" value="0.52" />
        </ParameterAssignments>
      </CatalogReference>
      <ObjectController>
        <Controller name="Autoware">
          <Properties>
            <Property name="maxJerk" value="1.5" />
            <Property name="minJerk" value="-1.5" />
          </Properties>
        </Controller>
      </ObjectController>
    </ScenarioObject>
  </Entities>
  <Storyboard>
    <Init>
      <Actions>
        <Private entityRef="ego">
          <PrivateAction>
            <TeleportAction>
              <Position><WorldPosition x="{s['x']}" y="{s['y']}" z="{s['z']}" h="{s['yaw']}" p="0" r="0" /></Position>
            </TeleportAction>
          </PrivateAction>
          <PrivateAction>
            <RoutingAction>
              <AcquirePositionAction><Position><WorldPosition x="{g['x']}" y="{g['y']}" z="{g['z']}" h="{g['yaw']}" p="0" r="0" /></Position></AcquirePositionAction>
            </RoutingAction>
          </PrivateAction>
        </Private>
      </Actions>
    </Init>
    <Story name="route{name}">
      <Act name="drive">
        <ManeuverGroup maximumExecutionCount="1" name="ego_maneuvers">
          <Actors selectTriggeringEntities="false"><EntityRef entityRef="ego" /></Actors>
          <Maneuver name="end_conditions">
            <Event name="success" priority="parallel">
              <Action name="exit_success"><UserDefinedAction><CustomCommandAction type="exitSuccess" /></UserDefinedAction></Action>
              <StartTrigger><ConditionGroup>
                <Condition name="reach_goal" delay="0" conditionEdge="none">
                  <ByEntityCondition><TriggeringEntities triggeringEntitiesRule="any"><EntityRef entityRef="ego" /></TriggeringEntities>
                    <EntityCondition><ReachPositionCondition tolerance="2.0"><Position><WorldPosition x="{g['x']}" y="{g['y']}" z="{g['z']}" h="{g['yaw']}" p="0" r="0" /></Position></ReachPositionCondition></EntityCondition>
                  </ByEntityCondition>
                </Condition>
              </ConditionGroup></StartTrigger>
            </Event>
            <Event name="timeout" priority="parallel">
              <Action name="exit_failure"><UserDefinedAction><CustomCommandAction type="exitFailure" /></UserDefinedAction></Action>
              <StartTrigger><ConditionGroup>
                <Condition name="timeout_condition" delay="0" conditionEdge="none">
                  <ByValueCondition><SimulationTimeCondition value="{timeout:.0f}" rule="greaterThan" /></ByValueCondition>
                </Condition>
              </ConditionGroup></StartTrigger>
            </Event>
          </Maneuver>
        </ManeuverGroup>
        <StartTrigger><ConditionGroup>
          <Condition name="start" delay="0" conditionEdge="none">
            <ByValueCondition><SimulationTimeCondition value="0" rule="greaterThan" /></ByValueCondition>
          </Condition>
        </ConditionGroup></StartTrigger>
      </Act>
    </Story>
    <StopTrigger />
  </Storyboard>
</OpenSCENARIO>
"""


def main():
    check = "--check" in sys.argv[1:]
    routes = yaml.safe_load((PKG / "config" / "routes.yaml").read_text())["routes"]
    stale = []
    for name, r in routes.items():
        out = PKG / "scenarios" / f"route{name}.xosc"
        text = scenario(name, r)
        if out.is_file() and out.read_text() == text:
            continue
        if check:
            stale.append(out)
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"wrote {out}")
    for p in stale:
        print(f"stale: {p}", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
