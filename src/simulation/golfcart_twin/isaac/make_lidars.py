#!/usr/bin/env python3
"""The cart's two lidars as Isaac Sim RTX lidar profiles (OmniLidar prims), for Phase 10.

    python3 make_lidars.py OUT_DIR [--vlp32-calibration VLP32.yaml]

Run with any Python that has pxr (Isaac Sim's own venv does). It writes:

- OUT_DIR/VLP32C.usda: the Velodyne VLP-32C on the roof. It is rotary, with 32 lasers at
  the elevations and azimuth offsets of Nebula's factory calibration
  (nebula_decoders/calibration/velodyne/VLP32.yaml, the file the cart's driver decodes
  with). It spins at 600 rpm (10 Hz, the cart's VLP32.param.yaml) with a single return, and
  ranges from 0.3 to 200 m.
- OUT_DIR/Falcon.usda: the Seyond (InnoFusion) Falcon on the front deck. It is solid-state,
  10 Hz, with the pattern measured on the cart's own scans (the 2026-08-20 GLIM mapping bags,
  /sensing/lidar/falcon/iv_points: 84-92 k points a frame, +-60 deg across and -14 to +11
  deg up). Its region of interest is about 3x denser in elevation between -3 and +2 deg
  and 2x in azimuth within +-20 deg. Here lines are 0.4 deg apart, 0.13 inside the band,
  with points 0.2 deg apart along a line, 0.1 within +-20 deg: 88 lines of 800, 70 k points.
  The steps are an estimate of the pattern, not the sensor's table.

Both emit along their prim's +x with +z up, as every Isaac lidar does. The Falcon's driver
publishes its points in the sensor's own axes (x up, y right, z forward, the driver's
coordinate_mode 0), and the cart's calibration places the `seyond` frame in those axes. So
the rig turns the emitter into that frame (see the rig's `emitter_rpy`); nothing here
depends on it.

The attribute set is that of NVIDIA's Example_Rotary.usda and Example_Solid_State.usda
(Isaac Sim 6.0 assets, Isaac/Sensors/NVIDIA/), the schema
OmniSensorGenericLidarCoreAPI.
"""
import argparse
import math
import os

import yaml
from pxr import Sdf, Usd

NEBULA_VLP32 = "/opt/autoware/1.5.0/share/nebula_decoders/calibration/velodyne/VLP32.yaml"

COMMON = {
    "omni:sensor:Core:accumulateOutputs": (Sdf.ValueTypeNames.Bool, True),
    "omni:sensor:Core:azimuthErrorMean": (Sdf.ValueTypeNames.Float, 0.0),
    "omni:sensor:Core:elevationErrorMean": (Sdf.ValueTypeNames.Float, 0.0),
    "omni:sensor:Core:intensityMappingType": (Sdf.ValueTypeNames.Token, "LINEAR"),
    "omni:sensor:Core:intensityProcessing": (Sdf.ValueTypeNames.Token, "NORMALIZATION"),
    "omni:sensor:Core:maxReturns": (Sdf.ValueTypeNames.UInt, 1),
    "omni:sensor:Core:minReflectance": (Sdf.ValueTypeNames.Float, 0.1),
    "omni:sensor:Core:pulseTimeNs": (Sdf.ValueTypeNames.UInt, 6),
    "omni:sensor:Core:rangeResolutionM": (Sdf.ValueTypeNames.Float, 0.004),
    "omni:sensor:Core:rayType": (Sdf.ValueTypeNames.Token, "IDEALIZED"),
    "omni:sensor:Core:rotationDirection": (Sdf.ValueTypeNames.Token, "CW"),
    "omni:sensor:Core:scanRateBaseHz": (Sdf.ValueTypeNames.UInt, 10),
    "omni:sensor:Core:skipDroppingInvalidPoints": (Sdf.ValueTypeNames.Bool, False),
    "omni:sensor:tickRate": (Sdf.ValueTypeNames.Float, 10.0),
}


def _write(path, name, scalars, emitters):
    """An OmniLidar prim `name`, the default prim of a new layer at `path`, with `scalars`
    ({attr: (type, value)}) and the emitter state s001 ({field: (type, list)})."""
    stage = Usd.Stage.CreateNew(path)
    stage.GetRootLayer().documentation = "Generated by golfcart_twin/isaac/make_lidars.py: do not edit"
    prim = stage.DefinePrim(f"/{name}", "OmniLidar")
    stage.SetDefaultPrim(prim)
    prim.AddAppliedSchema("OmniSensorGenericLidarCoreAPI")
    for attr, (t, v) in {**COMMON, **scalars}.items():
        prim.CreateAttribute(attr, t).Set(v)
    for field, (t, v) in emitters.items():
        prim.CreateAttribute(f"omni:sensor:Core:emitterState:s001:{field}", t).Set(v)
    prim.CreateAttribute("omni:sensor:modelName", Sdf.ValueTypeNames.String).Set(name)
    stage.GetRootLayer().Save()
    return len(next(iter(emitters.values()))[1])


def vlp32c(path, calibration):
    lasers = sorted(yaml.safe_load(open(calibration))["lasers"], key=lambda l: l["laser_id"])
    if len(lasers) != 32:
        raise SystemExit(f"{calibration}: {len(lasers)} lasers, a VLP-32C has 32")
    n = len(lasers)
    elevation = [math.degrees(l["vert_correction"]) for l in lasers]
    azimuth = [math.degrees(l["rot_correction"]) for l in lasers]
    # The VLP-32C fires two lasers at a time, 16 firings of 2.304 us in a 55.296 us cycle
    # (VLP-32C user manual, firing timing): 18083 firing cycles a second. The RTX lidar takes
    # a whole number of firing cycles per revolution (18083 at 10 Hz gave no points), so
    # 18000: 1800 a revolution, 0.2 deg apart, the VLP-32C's resolution at 600 rpm.
    # Their real spacing, 2.304 us (a 34.6 us cycle), gives no points at all: the RTX lidar
    # renders nothing when the fire times span more than about 25 us (bisected 2026-11-07;
    # NVIDIA's Example_Rotary spans 24.5). 1.5 us keeps the pairs and their order, 22.5 us
    # in all; the points carry no per-point time downstream anyway.
    fire = [(i // 2) * 1500 for i in range(n)]
    zeros = [0.0] * n
    scalars = {
        "omni:sensor:Core:numberOfChannels": (Sdf.ValueTypeNames.UInt, n),
        "omni:sensor:Core:numberOfEmitters": (Sdf.ValueTypeNames.UInt, n),
        "omni:sensor:Core:reportRateBaseHz": (Sdf.ValueTypeNames.UInt, 18000),
        "omni:sensor:Core:scanType": (Sdf.ValueTypeNames.Token, "ROTARY"),
        "omni:sensor:Core:startAzimuthOffsetDeg": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:nearRangeM": (Sdf.ValueTypeNames.Float, 0.3),
        "omni:sensor:Core:farRangeM": (Sdf.ValueTypeNames.Float, 200.0),
        "omni:sensor:Core:rangeAccuracyM": (Sdf.ValueTypeNames.Float, 0.03),
        "omni:sensor:Core:azimuthErrorStd": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:elevationErrorStd": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:peakPowerW": (Sdf.ValueTypeNames.Float, 0.002),
    }
    F, U = Sdf.ValueTypeNames.FloatArray, Sdf.ValueTypeNames.UIntArray
    emitters = {
        "azimuthDeg": (F, azimuth), "elevationDeg": (F, elevation),
        "channelId": (U, list(range(1, n + 1))), "fireTimeNs": (U, fire),
        "distanceCorrectionM": (F, zeros), "emitterPeakPowerW": (F, zeros),
        "focalDistM": (F, zeros), "focalSlope": (F, zeros),
        "horOffsetM": (F, zeros), "vertOffsetM": (F, zeros),
    }
    return _write(path, "VLP32C", scalars, emitters)


def _steps(lo, hi, band, coarse, fine):
    """Angles from lo to hi, `fine` apart inside `band` (lo, hi) and `coarse` outside."""
    out, a = [], lo
    while a <= hi + 1e-9:
        out.append(round(a, 4))
        a += fine if band[0] - 1e-9 <= a < band[1] else coarse
    return out


def falcon(path, rate_hz=10):
    lines = _steps(-14.0, 11.0, (-3.0, 2.0), 0.4, 0.13)[::-1]      # top line first
    cols = _steps(-60.0, 60.0, (-20.0, 20.0), 0.2, 0.1)
    az, el, bank, fire = [], [], [], []
    period_ns = int(1e9 / rate_hz)
    total = len(lines) * len(cols)
    for li, e in enumerate(lines):
        for c, a in enumerate(cols):
            az.append(a)
            el.append(e)
            bank.append(li)
            fire.append(int((li * len(cols) + c) * period_ns / total))
    n = len(az)
    zeros = [0.0] * n
    scalars = {
        "omni:sensor:Core:numberOfChannels": (Sdf.ValueTypeNames.UInt, n),
        "omni:sensor:Core:numberOfEmitters": (Sdf.ValueTypeNames.UInt, n),
        "omni:sensor:Core:numLines": (Sdf.ValueTypeNames.UInt, len(lines)),
        "omni:sensor:Core:numRaysPerLine": (Sdf.ValueTypeNames.UIntArray, [len(cols)] * len(lines)),
        "omni:sensor:Core:patternFiringRateHz": (Sdf.ValueTypeNames.UInt, rate_hz),
        "omni:sensor:Core:reportRateBaseHz": (Sdf.ValueTypeNames.UInt, rate_hz),
        "omni:sensor:Core:rangeCount": (Sdf.ValueTypeNames.UInt, 1),
        "omni:sensor:Core:stateResolutionStep": (Sdf.ValueTypeNames.UInt, 1),
        "omni:sensor:Core:focusDistM": (Sdf.ValueTypeNames.Float, 0.05),
        "omni:sensor:Core:scanType": (Sdf.ValueTypeNames.Token, "SOLID_STATE"),
        "omni:sensor:Core:nearRangeM": (Sdf.ValueTypeNames.Float, 0.4),
        "omni:sensor:Core:farRangeM": (Sdf.ValueTypeNames.Float, 250.0),
        "omni:sensor:Core:rangeAccuracyM": (Sdf.ValueTypeNames.Float, 0.02),
        "omni:sensor:Core:azimuthErrorStd": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:elevationErrorStd": (Sdf.ValueTypeNames.Float, 0.0),
        "omni:sensor:Core:peakPowerW": (Sdf.ValueTypeNames.Float, 0.06),
    }
    F, U = Sdf.ValueTypeNames.FloatArray, Sdf.ValueTypeNames.UIntArray
    emitters = {
        "azimuthDeg": (F, az), "elevationDeg": (F, el), "bank": (U, bank),
        "channelId": (U, list(range(1, n + 1))), "fireTimeNs": (U, fire),
        "rangeId": (U, [0] * n),
        "distanceCorrectionM": (F, zeros), "emitterPeakPowerW": (F, zeros),
        "focalDistM": (F, zeros), "focalSlope": (F, zeros),
        "horOffsetM": (F, zeros), "vertOffsetM": (F, zeros),
    }
    return _write(path, "Falcon", scalars, emitters)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out_dir")
    ap.add_argument("--vlp32-calibration", default=NEBULA_VLP32)
    a = ap.parse_args()
    os.makedirs(a.out_dir, exist_ok=True)
    for name, make in (("VLP32C.usda", lambda p: vlp32c(p, a.vlp32_calibration)),
                       ("Falcon.usda", falcon)):
        p = os.path.join(a.out_dir, name)
        if os.path.exists(p):
            os.remove(p)
        print(f"{p}: {make(p)} emitters")


if __name__ == "__main__":
    main()
