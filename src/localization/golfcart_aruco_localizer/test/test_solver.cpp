constexpr double kMarkerSize = 0.384;

Eigen::Matrix3d testIntrinsics()
{
  Eigen::Matrix3d k = Eigen::Matrix3d::Identity();
  k(0, 0) = 900.0;
  k(1, 1) = 900.0;
  k(0, 2) = 960.0;
  k(1, 2) = 640.0;
  return k;
}

/// Camera looking along base +x, optical convention (z forward, x right, y down).
Eigen::Isometry3d forwardCamera()
{
  Eigen::Isometry3d t = Eigen::Isometry3d::Identity();
  t.linear() = (Eigen::AngleAxisd(-M_PI_2, Eigen::Vector3d::UnitZ()) *
                Eigen::AngleAxisd(-M_PI_2, Eigen::Vector3d::UnitX()))
                 .toRotationMatrix();
  t.translation() = Eigen::Vector3d{0.0, 0.0, 0.6};
  return t;
}

/// Build an observation of a board placed so it lands at `cam_to_tag` for the
/// given vehicle pose. Pixels are generated by projecting the true corners, so
/// with no noise the solver's residual at the true pose is exactly zero.
BoardObservation makeBoard(
  std::uint32_t id, const Eigen::Isometry3d & map_to_base,
  const Eigen::Isometry3d & cam_to_tag, double corner_noise_px = 0.0,
  std::mt19937 * rng = nullptr)
{
  BoardObservation b;
  b.id = id;
  b.camera = "front";
  b.base_to_cam = forwardCamera();
  b.k = testIntrinsics();
  b.marker_size = kMarkerSize;
  b.position_stddev = 0.02;
  b.map_to_tag = map_to_base * b.base_to_cam * cam_to_tag;

  std::normal_distribution<double> noise(0.0, corner_noise_px);
  const auto local = tagLocalCorners(kMarkerSize);
  for (std::size_t c = 0; c < kNumCorners; ++c) {
    const Eigen::Vector3d x = cam_to_tag * local[c];
    Eigen::Vector2d uv{
      b.k(0, 0) * x.x() / x.z() + b.k(0, 2),
      b.k(1, 1) * x.y() / x.z() + b.k(1, 2)};
    if (rng != nullptr && corner_noise_px > 0.0) {
      uv.x() += noise(*rng);
      uv.y() += noise(*rng);
    }
    b.pixels[c] = uv;
  }

  // The true solution, plus a plausible flipped alternate.
  b.cam_to_tag_1 = cam_to_tag;
  b.error_1 = 0.01;
  Eigen::Isometry3d flipped = cam_to_tag;
  flipped.linear() = cam_to_tag.linear() *
    Eigen::AngleAxisd(0.6, Eigen::Vector3d::UnitX()).toRotationMatrix();
  b.cam_to_tag_2 = flipped;
  b.error_2 = 1.0;
  return b;
}

/// A board in front of the camera, tilted so the view is oblique.
Eigen::Isometry3d viewAt(double x, double y, double z, double tilt)
{
  Eigen::Isometry3d t = Eigen::Isometry3d::Identity();
  t.linear() = (Eigen::AngleAxisd(M_PI, Eigen::Vector3d::UnitY()) *
                Eigen::AngleAxisd(tilt, Eigen::Vector3d::UnitX()))
                 .toRotationMatrix();
  t.translation() = Eigen::Vector3d{x, y, z};
  return t;
}

Eigen::Isometry3d vehicleAt(double x, double y, double yaw)
{
  Eigen::Isometry3d t = Eigen::Isometry3d::Identity();
  t.linear() = Eigen::AngleAxisd(yaw, Eigen::Vector3d::UnitZ()).toRotationMatrix();
  t.translation() = Eigen::Vector3d{x, y, 0.0};
  return t;
}

std::vector<std::pair<std::size_t, int>> allTrue(std::size_t n)
{
  std::vector<std::pair<std::size_t, int>> f;
  for (std::size_t i = 0; i < n; ++i) {
    f.emplace_back(i, 0);
  }
  return f;
}

double angleBetween(const Eigen::Isometry3d & a, const Eigen::Isometry3d & b)
{
  return std::abs(Eigen::AngleAxisd(a.linear().transpose() * b.linear()).angle());
}

